// The SQL that puts the demo's fake data back to a fresh state: it removes every demo row
// (ids starting de000000-) and loads them again with today's dates, in one go.
//
//   npm run -s demo:reset-sql | pbcopy      then paste into the DEMO project's SQL editor and run
//
// It refuses to run, and changes nothing, on a database without demo data: Khyati's live project.
// Real rows (anything you added yourself) are never touched.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const read = (f) => fs.readFileSync(new URL(`../supabase/demo/${f}`, import.meta.url), 'utf8');

export function resetSql() {
  return [
    '-- Reset the Covaro demo: generated by scripts/demo-reset.mjs. Run on the DEMO project only.',
    'do $$',
    'begin',
    "  if not exists (select 1 from candidates where id::text like 'de000000-%') then",
    "    raise exception 'No demo data here, so this is not the demo database. Nothing was changed.';",
    '  end if;',
    'end $$;',
    '',
    read('remove_demo_data.sql'),
    '',
    read('demo_data.sql'),
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.stdout.write(resetSql());
